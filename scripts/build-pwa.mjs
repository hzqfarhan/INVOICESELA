import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publicRoot = path.join(projectRoot, 'public');
const outputRoot = path.join(projectRoot, 'out');
const logoPath = path.join(publicRoot, 'brand', 'seladevs-logo.png');

// Build after Next's static export, which copies public/ before these icons exist.
// Write both destinations so the current export and subsequent builds have them.
await stat(path.join(outputRoot, 'index.html'));
await Promise.all([
  mkdir(path.join(publicRoot, 'icons'), { recursive: true }),
  mkdir(path.join(outputRoot, 'icons'), { recursive: true }),
]);

const logo = await sharp(logoPath).rotate().trim({ threshold: 8 }).toBuffer();
const iconSpecs = [
  { name: 'icon-192.png', size: 192, contentScale: 0.8 },
  { name: 'icon-512.png', size: 512, contentScale: 0.8 },
  // All content stays inside the central safe area when a launcher masks it.
  { name: 'maskable-512.png', size: 512, contentScale: 0.62 },
  { name: 'apple-touch-icon.png', size: 180, contentScale: 0.78 },
];

for (const { name, size, contentScale } of iconSpecs) {
  const contentSize = Math.round(size * contentScale);
  const mark = await sharp(logo)
    .resize(contentSize, contentSize, { fit: 'inside', withoutEnlargement: false })
    .toBuffer();
  const icon = await sharp({
    create: { width: size, height: size, channels: 4, background: '#ffffff' },
  })
    .composite([{ input: mark, gravity: 'centre' }])
    .flatten({ background: '#ffffff' })
    .png()
    .toBuffer();
  await Promise.all([
    writeFile(path.join(publicRoot, 'icons', name), icon),
    writeFile(path.join(outputRoot, 'icons', name), icon),
  ]);
}

async function listOutputFiles(directory, relative = '') {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const name = relative ? `${relative}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      files.push(...await listOutputFiles(path.join(directory, entry.name), name));
    } else if (entry.isFile() && name !== 'sw.js' && !name.endsWith('.map')) {
      files.push(name);
    }
  }
  return files.sort();
}

const files = await listOutputFiles(outputRoot);
const essentialFiles = [
  'index.html',
  'manifest.webmanifest',
  'brand/seladevs-logo.png',
  ...iconSpecs.map(icon => `icons/${icon.name}`),
];
for (const essential of essentialFiles) {
  if (!files.includes(essential)) throw new Error(`PWA build is missing ${essential}`);
}

const hash = createHash('sha256');
for (const file of files) {
  hash.update(file);
  hash.update('\0');
  hash.update(await readFile(path.join(outputRoot, ...file.split('/'))));
  hash.update('\0');
}
const version = hash.digest('hex').slice(0, 20);
const precacheUrls = [...new Set([
  '/',
  ...files.map(file => `/${file.split('/').map(encodeURIComponent).join('/')}`),
])];

const worker = `/* Generated by scripts/build-pwa.mjs. */
const CACHE_PREFIX = 'seladevs-invoice-';
const CACHE_NAME = CACHE_PREFIX + ${JSON.stringify(version)};
const PRECACHE_URLS = ${JSON.stringify(precacheUrls, null, 2)};
const STATIC_URLS = new Set(PRECACHE_URLS.filter(url => url !== '/' && !url.endsWith('.html')));

function isOwnResponse(response) {
  return response.ok && response.type !== 'opaque' &&
    (!response.url || new URL(response.url).origin === self.location.origin);
}

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    // Precache every exported file, including all JS, CSS and font chunks.
    // First-load requests often finish before the worker gains control.
    await cache.addAll(PRECACHE_URLS.map(url => new Request(url, {
      cache: 'reload', credentials: 'same-origin'
    })));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys
      .filter(key => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME)
      .map(key => caches.delete(key)));
    await self.clients.claim();
  })());
});

async function navigationResponse(request) {
  const cache = await caches.open(CACHE_NAME);
  try {
    const response = await fetch(request);
    if (isOwnResponse(response)) {
      await cache.put(request, response.clone()).catch(() => {});
      return response;
    }
    // Preserve real client errors; temporary server failures can use the app shell.
    if (response.status < 500) return response;
    return await cache.match(request) || await cache.match('/') || response;
  } catch {
    return await cache.match(request) || await cache.match('/') ||
      new Response('Seladevs Invoice Studio is unavailable offline. Open it once while online.', {
        status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8' }
      });
  }
}

async function staticResponse(request) {
  const cache = await caches.open(CACHE_NAME);
  const cached = await cache.match(request);
  if (cached) return cached;
  const response = await fetch(request);
  if (isOwnResponse(response)) await cache.put(request, response.clone()).catch(() => {});
  return response;
}

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(navigationResponse(request));
  } else if (url.pathname.startsWith('/_next/static/') || STATIC_URLS.has(url.pathname)) {
    event.respondWith(staticResponse(request));
  }
});
`;

await Promise.all([
  writeFile(path.join(outputRoot, 'sw.js'), worker),
  writeFile(path.join(publicRoot, 'sw.js'), worker),
]);

console.log(`PWA ready: ${iconSpecs.length} icons, ${precacheUrls.length} offline assets, version ${version}.`);
